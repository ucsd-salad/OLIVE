"""Protocol core and query-vocabulary extension, built only from fixed formats.

A verifier file never copies protocol text; it opens modules this file writes:

    <name>_core.als   the protocol without its standalone section   (build_core)
    query_ext.als     new query words, opening the core             (build_extension)

Three guarantees hold by construction, and each is checked:

1. Direction. The extension opens the core; the core opens no local module. The
   program writes every `open` line, so the cycle core -> extension -> core that
   Alloy rejects cannot be written.
2. The core never says the rules hold. It is cut from the protocol file at the
   "// STANDALONE MODE" marker, and check_core rejects any fact (a signature fact
   included) that mentions `Protocol` or a rule predicate, and any command. A
   fact like `fact ProtocolHolds { Protocol }` would make `not Protocol`
   unsatisfiable, so every plan would pass.
3. The extension only adds words. The model supplies declaration lines in one
   of three forms (EXTENSION_FORMAT); any other line is rejected, and so is a
   name the core already uses. So it cannot add a fact, change or extend an
   existing signature, or shadow an existing name.
"""

from __future__ import annotations

import re
from pathlib import Path


STANDALONE_MARKER = "// STANDALONE MODE"
GENERATED = "// GENERATED by protocol_modules"
EXTENSION_MODULE = "query_ext"
EXTENSION_SIG = "QueryExt"

COMMAND = re.compile(r"(?m)^\s*(?:run|check)\b")
KEYWORDS = {
    "abstract", "all", "and", "as", "assert", "but", "check", "disj", "else", "enum",
    "exactly", "expect", "extends", "fact", "for", "fun", "iden", "iff", "implies",
    "in", "Int", "int", "let", "lone", "module", "no", "none", "not", "one", "open",
    "or", "pred", "private", "run", "seq", "set", "sig", "some", "String", "sum",
    "this", "univ", "var", "always", "eventually", "after", "before", "once",
    "historically", "until", "releases", "since", "triggered", "steps",
}
# names the verifier files themselves declare
RESERVED = {"Protocol", "GeneratedPlan", "Query", "CounterExample", "PlanPossible", EXTENSION_SIG}


class ProtocolError(ValueError):
    pass


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return "\n".join(re.split(r"//|--", line, maxsplit=1)[0] for line in text.splitlines())


def split_protocol(text: str) -> tuple[str, str]:
    """(core, standalone). A protocol with commands must mark where its
    standalone section starts; guessing the cut would risk keeping a fact that
    asserts the rules."""
    index = text.find(STANDALONE_MARKER)
    if index < 0:
        if COMMAND.search(strip_comments(text)):
            raise ProtocolError(
                "the protocol has run/check commands but no %r line marking its "
                "standalone section" % STANDALONE_MARKER)
        return text.rstrip() + "\n", ""
    line_start = text.rfind("\n", 0, index) + 1
    lines = text[:line_start].rstrip().splitlines()
    while lines and re.fullmatch(r"//\s*=+", lines[-1].strip()):   # the section's banner
        lines.pop()
    return "\n".join(lines).rstrip() + "\n", text[line_start:]


def protocol_rules(code: str) -> list[str]:
    """The rule names conjoined in `pred Protocol { ... }`, in order."""
    match = re.search(r"(?m)^pred\s+Protocol\s*\{(.*?)^\}", code, re.S)
    if not match:
        return []
    return re.findall(r"\b([A-Za-z_]\w*)\b", strip_comments(match.group(1)))


def _block(text: str, open_index: int) -> tuple[str, int]:
    """The text inside the brace at open_index, and the index after its close."""
    depth = 0
    for index in range(open_index, len(text)):
        if text[index] == "{":
            depth += 1
        elif text[index] == "}":
            depth -= 1
            if depth == 0:
                return text[open_index + 1:index], index + 1
    raise ProtocolError("unbalanced braces")


SIG_HEADER = re.compile(
    r"(?m)^\s*(?:(?:abstract|one|lone|some|private|var)\s+)*sig\s+([\w\s,]+?)\s*"
    r"(?:\bextends\s+\w+|\bin\s+[\w\s+]+?)?\s*\{")


def signatures(text: str) -> list[tuple[list[str], str, str]]:
    """(names, body, signature fact) of every signature declaration."""
    code = strip_comments(text)
    found = []
    for match in SIG_HEADER.finditer(code):
        body, after = _block(code, match.end() - 1)
        rest = code[after:].lstrip()
        sig_fact = _block(rest, 0)[0] if rest.startswith("{") else ""
        names = [n.strip() for n in match.group(1).split(",") if n.strip()]
        found.append((names, body, sig_fact))
    return found


def declared_names(text: str) -> set[str]:
    """Every name a module declares: signatures, fields, enums and their values,
    predicates, functions, assertions and named facts."""
    code = strip_comments(text)
    names = set()
    for sig_names, body, _ in signatures(text):
        names.update(sig_names)
        for group in re.findall(r"(?:^|,)\s*((?:[A-Za-z_]\w*\s*,\s*)*[A-Za-z_]\w*)\s*:", body):
            names.update(n.strip() for n in group.split(","))
    for enum_name, values in re.findall(r"(?m)^\s*enum\s+(\w+)\s*\{([^}]*)\}", code):
        names.add(enum_name)
        names.update(v.strip() for v in values.split(",") if v.strip())
    names.update(re.findall(r"(?m)^\s*(?:private\s+)?(?:pred|fun|assert|fact)\s+(?:\w+\.)?(\w+)", code))
    return names


def rule_predicates(core: str) -> set[str]:
    """`Protocol`, its rules, and every predicate or function they use,
    transitively: the vocabulary of the safety obligations."""
    code = strip_comments(core)
    bodies = {}
    for match in re.finditer(r"(?m)^\s*(?:private\s+)?(?:pred|fun)\s+(\w+)[^{]*\{", code):
        bodies[match.group(1)] = _block(code, match.end() - 1)[0]
    reached, frontier = set(), ["Protocol"]
    while frontier:
        name = frontier.pop()
        if name in reached:
            continue
        reached.add(name)
        frontier.extend(w for w in re.findall(r"\b\w+\b", bodies.get(name, "")) if w in bodies)
    return reached


def check_core(core: str) -> list[str]:
    """Why `core` may not be opened by a verifier; empty when it may."""
    problems = []
    code = strip_comments(core)
    rules = protocol_rules(core)
    if not rules:
        problems.append("no `pred Protocol { ... }` listing the safety rules")
    if COMMAND.search(code):
        problems.append("contains run/check commands")
    for target in re.findall(r"(?m)^\s*open\s+([\w/]+)", code):
        if not target.startswith("util/"):
            problems.append("opens the local module %r (a core may open only util/ modules)" % target)
    # a fact that states the rules, or any predicate they are built from, would
    # hide violations: only structural constraints may be facts
    asserted = rule_predicates(core) | set(rules)
    bodies = []
    for match in re.finditer(r"(?m)^\s*fact\b[^{]*\{", code):
        name = code[match.start():match.end() - 1].split("fact", 1)[1].strip() or "(unnamed)"
        bodies.append(("fact " + name, _block(code, match.end() - 1)[0]))
    for sig_names, _, sig_fact in signatures(core):
        if sig_fact:
            bodies.append(("signature fact of " + ", ".join(sig_names), sig_fact))
    for label, body in bodies:
        used = sorted(asserted & set(re.findall(r"\b\w+\b", body)))
        if used:
            problems.append("%s uses %s, part of the safety rules: a fact may only state "
                            "structure, or violations of those rules could never be found"
                            % (label, ", ".join(used)))
    return problems


def _block_raw(text: str, open_index: int) -> int:
    """Index after the brace matching the one at open_index, skipping comments."""
    depth, index = 0, open_index
    while index < len(text):
        if text.startswith("//", index) or text.startswith("--", index):
            index = text.find("\n", index)
            index = len(text) if index < 0 else index
            continue
        if text.startswith("/*", index):
            end = text.find("*/", index + 2)
            index = len(text) if end < 0 else end + 2
            continue
        if text[index] == "{":
            depth += 1
        elif text[index] == "}":
            depth -= 1
            if depth == 0:
                return index + 1
        index += 1
    raise ProtocolError("unbalanced braces")


def vocabulary_view(core: str) -> str:
    """The words of a protocol, without its rules: the leading block comment
    (units, scaling) and every signature and enum declaration with the comment
    lines directly above it. This is what a formalizer is shown: a query states
    facts in these words and may not call the protocol's predicates."""
    parts = []
    header = re.match(r"\s*/\*.*?\*/", core, re.S)
    if header:
        parts.append(header.group(0).strip())
    lines = core.splitlines(keepends=True)
    offsets = [0]
    for line in lines:
        offsets.append(offsets[-1] + len(line))
    declaration = re.compile(
        r"^\s*(?:(?:abstract|one|lone|some|private|var)\s+)*(?:sig|enum)\b")
    for number, line in enumerate(lines):
        if not declaration.match(line):
            continue
        start = offsets[number]
        brace = core.find("{", start)
        end = _block_raw(core, brace)
        above = number
        while above > 0 and lines[above - 1].strip().startswith("//"):
            above -= 1
        parts.append((core[offsets[above]:start] + core[start:end]).strip())
    return "\n\n".join(parts) + "\n"


def predicate_names(core: str) -> set[str]:
    """Every predicate and function a protocol declares."""
    return set(re.findall(r"(?m)^\s*(?:private\s+)?(?:pred|fun)\s+(?:\w+\.)?(\w+)",
                          strip_comments(core)))


def protocol_scope(text: str, default: str = "for 5 but 9 Int") -> str:
    """The scope a protocol's own commands use (its standalone section), so a
    query or a plan is checked at the size its author validated the model at."""
    try:
        tail = split_protocol(text)[1]
    except ProtocolError:
        tail = text
    scopes = re.findall(r"\bfor\s+\d+(?:\s+but\s+[^\n{}]+)?", strip_comments(tail))
    if not scopes:
        return default
    return max((scope.strip().rstrip(",") for scope in scopes), key=len)


def module_name(text: str) -> str:
    match = re.search(r"(?m)^\s*module\s+([\w/]+)", strip_comments(text))
    return match.group(1) if match else ""


def core_name(protocol_path: str | Path) -> str:
    """Module name of a protocol's core, e.g. safety_protocol.als -> safety_protocol_core."""
    return re.sub(r"\W", "_", Path(protocol_path).stem) + "_core"


def build_core(protocol_path: str | Path, out_dir: str | Path) -> Path:
    """Write <stem>_core.als: the protocol up to its standalone section, as a
    module a verifier or an extension can open."""
    protocol_path, out_dir = Path(protocol_path), Path(out_dir)
    core, _ = split_protocol(protocol_path.read_text(encoding="utf-8"))
    core = re.sub(r"(?m)^\s*module\s+[\w/]+.*\n", "", core, count=1)
    problems = check_core(core)
    if problems:
        raise ProtocolError("%s cannot be used as a protocol core:\n- %s"
                            % (protocol_path.name, "\n- ".join(problems)))
    name = core_name(protocol_path)
    path = out_dir / f"{name}.als"
    path.write_text(
        f"module {name}\n"
        f"{GENERATED} from {protocol_path.name}: do not edit.\n"
        f"// The section from {STANDALONE_MARKER!r} on was cut off; it lives in the source file.\n\n"
        + core, encoding="utf-8")
    return path


# ---------------------------------------------------------------- extension

EXTENSION_FORMAT = """\
One new word per line, each line exactly one of these three forms:
  <newName>: set <Sig>                -- <what it means>
  <newName>: <Sig> -> lone Int        -- <what it means>
  <newName>: <Sig> -> lone <Sig2>     -- <what it means>
<newName> starts with a lower-case letter and is not a name the protocol already
uses (compared ignoring case); <Sig> and <Sig2> are signatures the protocol declares. Write nothing else:
no fact, pred, sig, open or braces. A new word is used as `x in QueryExt.<newName>`
(set form) or `x.(QueryExt.<newName>)` (the other two forms)."""

NAME = r"([a-z][A-Za-z0-9_]*)"
SIG = r"([A-Z][A-Za-z0-9_]*)"
FORMS = (
    re.compile(rf"^{NAME}\s*:\s*set\s+{SIG}$"),
    re.compile(rf"^{NAME}\s*:\s*{SIG}\s*->\s*lone\s+(Int)$"),
    re.compile(rf"^{NAME}\s*:\s*{SIG}\s*->\s*lone\s+{SIG}$"),
)


def check_extension_lines(lines: list[str], core: str) -> tuple[list[tuple[str, str, str]], list[str]]:
    """(name, declaration, meaning) of every accepted line, and every problem."""
    sig_names = {n for names, _, _ in signatures(core) for n in names}
    # compared ignoring case: `spa` next to the signature `Spa` is legal Alloy but
    # an easy confusion for whoever reads the formal query
    taken = {n.lower() for n in declared_names(core) | KEYWORDS | RESERVED}
    accepted, problems, seen = [], [], set()
    for raw in lines:
        line = raw.strip()
        if not line:
            continue
        declaration, separator, meaning = line.partition("--")
        declaration = " ".join(declaration.split()).rstrip(",").strip()
        meaning = meaning.strip()
        match = next((m for form in FORMS if (m := form.match(declaration))), None)
        if match is None:
            problems.append("%r is not one of the three extension forms" % line)
            continue
        name, *types = match.groups()
        if not separator or not meaning:
            problems.append("%r has no `-- <what it means>` description" % line)
        if name.lower() in taken:
            problems.append("%r: the name %r is already used by the protocol or reserved" % (line, name))
        if name in seen:
            problems.append("%r: the name %r is declared twice" % (line, name))
        for sig in types:
            if sig != "Int" and sig not in sig_names:
                problems.append("%r: %r is not a signature of the protocol" % (line, sig))
        seen.add(name)
        accepted.append((name, declaration.split(":", 1)[1].strip(), meaning))
    if not accepted and not problems:
        problems.append("no extension lines")
    return accepted, problems


def extension_block(accepted: list[tuple[str, str, str]]) -> str:
    """The container signature holding checked extension words."""
    # the separating comma goes before the comment: after it, it would be commented out
    fields = "\n".join(
        f"  {name}: {declaration}{',' if index < len(accepted) - 1 else ''}  -- {meaning}"
        for index, (name, declaration, meaning) in enumerate(accepted))
    return (f"{GENERATED}: new query words only. No protocol rule mentions them,\n"
            f"// so a fact stated with them is not checked against the protocol.\n"
            f"one sig {EXTENSION_SIG} {{\n{fields}\n}}\n")


def build_extension(lines: list[str], core_path: str | Path, module: str = EXTENSION_MODULE) -> Path:
    """Write <module>.als beside the core from checked lines. The header, the
    one `open` and the container signature are fixed; only the checked lines vary."""
    core_path = Path(core_path)
    core = core_path.read_text(encoding="utf-8")
    accepted, problems = check_extension_lines(lines, core)
    if problems:
        raise ProtocolError("extension rejected:\n- " + "\n- ".join(problems))
    path = core_path.with_name(f"{module}.als")
    path.write_text(f"module {module}\nopen {module_name(core)}\n\n" + extension_block(accepted),
                    encoding="utf-8")
    return path


def extension_words(path: str | Path) -> list[tuple[str, str]]:
    """(name, meaning) of every word in a built extension."""
    text = Path(path).read_text(encoding="utf-8")
    return re.findall(r"(?m)^\s+([a-z]\w*):[^\n]*?--\s*(.+?)\s*$", text)
